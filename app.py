
from flask import Flask, render_template, request, jsonify, redirect, url_for, session, flash
from werkzeug.security import generate_password_hash, check_password_hash
from functools import wraps
from collections import deque
from contextlib import contextmanager
import sqlite3
import os

app = Flask(__name__)

app.secret_key = os.environ.get(
    "NETTWIN_SECRET_KEY",
    "local-demo-secret-change-before-deployment"
)

DATABASE_URL = os.environ.get("DATABASE_URL")
DB = "net twin.db"

if DATABASE_URL:
    import psycopg
    from psycopg.rows import dict_row


@contextmanager
def database():
    if DATABASE_URL:
        db = psycopg.connect(DATABASE_URL, row_factory=dict_row)
    else:
        db = sqlite3.connect(DB)
        db.row_factory = sqlite3.Row

    try:
        yield db
        db.commit()
    except Exception:
        db.rollback()
        raise
    finally:
        db.close()


def sql(query):
    if DATABASE_URL:
        return query.replace("?", "%s")
    return query


def setup_database():
    with database() as db:
        if DATABASE_URL:
            db.execute("""
                CREATE TABLE IF NOT EXISTS users (
                    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    name TEXT NOT NULL,
                    email TEXT UNIQUE NOT NULL,
                    password TEXT NOT NULL
                )
            """)
        else:
            db.execute("""
                CREATE TABLE IF NOT EXISTS users (
                    id INTEGER PRIMARY KEY AUTOINCREMENT,
                    name TEXT NOT NULL,
                    email TEXT UNIQUE NOT NULL,
                    password TEXT NOT NULL
                )
            """)

        db.execute("""
            CREATE TABLE IF NOT EXISTS subscriptions (
                user_id INTEGER PRIMARY KEY,
                plan TEXT DEFAULT 'Free',
                billing TEXT DEFAULT 'Free',
                status TEXT DEFAULT 'Active',
                payment_method TEXT DEFAULT 'None',
                FOREIGN KEY (user_id) REFERENCES users(id)
            )
        """)


def login_required(function):
    @wraps(function)
    def wrapper(*args, **kwargs):
        if "user_id" not in session:
            if request.path.startswith("/api/"):
                return jsonify({"error": "Please log in."}), 401
            return redirect(url_for("login"))
        return function(*args, **kwargs)
    return wrapper


@app.route("/")
def home():
    if "user_id" in session:
        return redirect(url_for("dashboard"))
    return redirect(url_for("login"))


@app.route("/signup", methods=["GET", "POST"])
def signup():
    if request.method == "POST":
        name = request.form.get("name", "").strip()
        email = request.form.get("email", "").strip().lower()
        password = request.form.get("password", "")

        if not name or "@" not in email or len(password) < 8:
            flash(
                "Enter valid details and a password "
                "of at least 8 characters."
            )
            return redirect(url_for("signup"))

        try:
            with database() as db:
                if DATABASE_URL:
                    cursor = db.execute(
                        sql("""
                            INSERT INTO users (name, email, password)
                            VALUES (?, ?, ?)
                            RETURNING id
                        """),
                        (name, email, generate_password_hash(password))
                    )
                    user_id = cursor.fetchone()["id"]
                else:
                    cursor = db.execute(
                        """
                        INSERT INTO users (name, email, password)
                        VALUES (?, ?, ?)
                        """,
                        (name, email, generate_password_hash(password))
                    )
                    user_id = cursor.lastrowid

                db.execute(
                    sql("""
                        INSERT INTO subscriptions (user_id)
                        VALUES (?)
                    """),
                    (user_id,)
                )

            session.clear()
            session["user_id"] = user_id
            session["name"] = name

            return redirect(url_for("dashboard"))

        except Exception as error:
            if (
                isinstance(error, sqlite3.IntegrityError)
                or (
                    DATABASE_URL
                    and isinstance(error, psycopg.errors.UniqueViolation)
                )
            ):
                flash("This email is already registered.")
            else:
                app.logger.exception("Signup failed")
                flash("Signup failed. Please try again.")

    return render_template("login.html", mode="signup")


@app.route("/login", methods=["GET", "POST"])
def login():
    if request.method == "POST":
        email = request.form.get("email", "").strip().lower()
        password = request.form.get("password", "")

        with database() as db:
            user = db.execute(
                sql("SELECT * FROM users WHERE email = ?"),
                (email,)
            ).fetchone()

        if user and check_password_hash(user["password"], password):
            session.clear()
            session["user_id"] = user["id"]
            session["name"] = user["name"]

            return redirect(url_for("dashboard"))

        flash("Incorrect email or password.")

    return render_template("login.html", mode="login")


@app.route("/logout")
def logout():
    session.clear()
    return redirect(url_for("login"))


@app.route("/dashboard")
@login_required
def dashboard():
    with database() as db:
        subscription = db.execute(
            sql("""
                SELECT * FROM subscriptions
                WHERE user_id = ?
            """),
            (session["user_id"],)
        ).fetchone()

    return render_template(
        "index.html",
        user_name=session["name"],
        subscription=subscription
    )


def simulate_network(devices, links, failed_id):
    graph = {}

    for device in devices:
        graph[device["id"]] = []

    for link in links:
        a = link["from"]
        b = link["to"]

        if a != failed_id and b != failed_id:
            if a in graph and b in graph:
                graph[a].append(b)
                graph[b].append(a)

    routers = [
        d["id"]
        for d in devices
        if d["type"] == "Router" and d["id"] != failed_id
    ]

    visited = set()
    queue = deque(routers)

    while queue:
        current = queue.popleft()

        if current in visited:
            continue

        visited.add(current)

        for neighbour in graph.get(current, []):
            if neighbour not in visited:
                queue.append(neighbour)

    affected = []

    for device in devices:
        if device["id"] == failed_id:
            continue

        if device["type"] != "Router":
            if device["id"] not in visited:
                affected.append(device)

    return affected


@app.route("/api/simulate", methods=["POST"])
@login_required
def simulate():
    data = request.get_json(silent=True) or {}

    devices = data.get("devices", [])
    links = data.get("links", [])
    failed_id = data.get("failed_id")

    selected = next(
        (d for d in devices if d["id"] == failed_id),
        None
    )

    if selected is None:
        return jsonify({"error": "Invalid device"}), 400

    affected = simulate_network(
        devices,
        links,
        failed_id
    )

    unaffected = [
        d for d in devices
        if d["id"] != failed_id and d not in affected
    ]

    return jsonify({
        "failed": selected,
        "affected": affected,
        "unaffected": unaffected,
        "explanation": (
            f"{selected['name']} became unavailable. "
            f"{len(affected)} devices lost access "
            "to an available router."
        ),
        "recommendation": (
            "Inspect the failed device and its connections. "
            "Consider adding an alternative network path."
        )
    })


@app.route("/api/checkout", methods=["POST"])
@login_required
def checkout():
    data = request.get_json(silent=True) or {}

    plan = data.get("plan")
    billing = data.get("billing")

    if plan not in ["Free", "Basic", "Premium"]:
        return jsonify({"error": "Invalid plan"}), 400

    if plan == "Free":
        billing = "Free"
        payment = "None"

    else:
        if billing == "Annual":
            billing = "Yearly"

        if billing not in ["Monthly", "Yearly"]:
            return jsonify({
                "error": "Invalid billing cycle"
            }), 400

        payment = "Debit Card (Demo Only)"

    # Demo checkout: no real payment is processed.
    with database() as db:
        db.execute(
            sql("""
                UPDATE subscriptions
                SET plan = ?,
                    billing = ?,
                    status = 'Active',
                    payment_method = ?
                WHERE user_id = ?
            """),
            (
                plan,
                billing,
                payment,
                session["user_id"]
            )
        )

    return jsonify({
        "message": (
            "Demo subscription updated successfully. "
            "No payment was charged."
        ),
        "plan": plan,
        "billing": billing,
        "status": "Active",
        "payment_method": payment
    })


